CREATE OR REPLACE TABLE WH_RETAIL_DEV.STG_DDL.PRODUCTS (
    PRODUCT_ID NUMBER(38,0) NOT NULL PRIMARY KEY,
    SKU VARCHAR(50) NOT NULL UNIQUE,
    PRODUCT_NAME VARCHAR(200) NOT NULL,
    CATEGORY_ID NUMBER(38,0) NOT NULL,
    PRICE NUMBER(10,2) NOT NULL CHECK (PRICE >= 0),
    COST_PRICE NUMBER(10,2) DEFAULT 0.00,
    STOCK_QUANTITY NUMBER(18,0) NOT NULL DEFAULT 0,
    IS_ACTIVE BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT FK_PRODUCTS_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES WH_RETAIL_DEV.STG_DDL.CATEGORIES(CATEGORY_ID)
);
