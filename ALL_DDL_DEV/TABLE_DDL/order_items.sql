
CREATE OR REPLACE TABLE retail_analytics_db.STG.ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER(38,0) NOT NULL PRIMARY KEY,
    ORDER_ID NUMBER(38,0) NOT NULL,
    PRODUCT_ID NUMBER(38,0) NOT NULL,
    QUANTITY NUMBER(18,0) NOT NULL CHECK (QUANTITY > 0),
    UNIT_PRICE NUMBER(10,2) NOT NULL CHECK (UNIT_PRICE >= 0),
    LINE_TOTAL NUMBER(12,2) NOT NULL DEFAULT 0.00,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT FK_ORDER_ITEMS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES retail_analytics_db.STG.ORDERS(ORDER_ID),
    CONSTRAINT FK_ORDER_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES retail_analytics_db.STG.PRODUCTS(PRODUCT_ID)
);
