use warehouse WH_RETAIL_DEV;
CREATE OR REPLACE TABLE WH_RETAIL_DEV.STG_DDL.ORDERS (
    ORDER_ID NUMBER(38,0) NOT NULL PRIMARY KEY,
    CUSTOMER_ID NUMBER(38,0) NOT NULL,
    STORE_ID NUMBER(38,0) NOT NULL,
    ORDER_DATE TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    ORDER_STATUS VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    TOTAL_AMOUNT NUMBER(12,2) NOT NULL DEFAULT 0.00,
    PAYMENT_STATUS VARCHAR(30) NOT NULL DEFAULT 'UNPAID',
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES WH_RETAIL_DEV.STG_DDL.CUSTOMERS(CUSTOMER_ID),
    CONSTRAINT FK_ORDERS_STORE FOREIGN KEY (STORE_ID) REFERENCES WH_RETAIL_DEV.STG_DDL.STORES(STORE_ID)
);
